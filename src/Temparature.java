public class Temparature {


    public static void main(String[] args) {

        // Input
        double celsius = 36.50;

        // Process
        double kelvin = celsius + 273.15;
        double fahrenheit = celsius * 1.80 + 32.00;

        // Output
        System.out.println(kelvin);
        System.out.println(fahrenheit);
    }
}
